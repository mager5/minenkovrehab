-- Apply to an EMPTY migration database, never on the existing Supabase database.
-- UUIDs have defaults only for new records. Import must explicitly supply old IDs.
BEGIN;
CREATE SCHEMA rehab;
REVOKE ALL ON SCHEMA rehab FROM PUBLIC;

CREATE TABLE rehab.users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL,
  email_confirmed_at timestamptz,
  banned_until timestamptz,
  deleted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Keep imported identities distinct; ambiguous email matching must fail closed.
CREATE INDEX users_email_lookup ON rehab.users (lower(email));
CREATE TABLE rehab.credentials (
  user_id uuid PRIMARY KEY REFERENCES rehab.users(id),
  password_hash text NOT NULL,
  algorithm text NOT NULL CHECK (algorithm IN ('bcrypt', 'argon2id'))
);
CREATE TABLE rehab.profiles (
  id uuid PRIMARY KEY REFERENCES rehab.users(id),
  email text NOT NULL,
  full_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE rehab.products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug text NOT NULL UNIQUE,
  title text NOT NULL,
  description text,
  price numeric(14,2) NOT NULL CHECK (price > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE rehab.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invoice_id bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE CHECK (invoice_id > 0),
  product_id uuid NOT NULL REFERENCES rehab.products(id),
  buyer_email text NOT NULL,
  user_id uuid REFERENCES rehab.users(id),
  amount numeric(14,2) NOT NULL CHECK (amount > 0),
  currency text NOT NULL DEFAULT 'RUB' CHECK (currency = 'RUB'),
  mode text NOT NULL CHECK (mode IN ('test', 'live')),
  expected_shp jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','paid','refunded','cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  paid_at timestamptz,
  UNIQUE (id, product_id, mode),
  UNIQUE (id, amount, mode)
);
CREATE TABLE rehab.payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL UNIQUE REFERENCES rehab.orders(id),
  amount numeric(14,2) NOT NULL CHECK (amount > 0),
  mode text NOT NULL CHECK (mode IN ('test','live')),
  received_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (order_id, amount, mode) REFERENCES rehab.orders(id, amount, mode)
);
-- Mirrors actual dump fields; legacy purchases may have no corresponding order.
-- Do not deduplicate historical invoices or user/product pairs during import.
CREATE TABLE rehab.purchases (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES rehab.profiles(id),
  product_id uuid NOT NULL REFERENCES rehab.products(id),
  status text NOT NULL CHECK (status IN ('active','expired','refunded')),
  robokassa_invoice_id text,
  created_at timestamptz NOT NULL DEFAULT now(),
  order_id uuid UNIQUE,
  mode text NOT NULL CHECK (mode IN ('test','live')),
  expires_at timestamptz,
  FOREIGN KEY (order_id, product_id, mode) REFERENCES rehab.orders(id, product_id, mode)
);
CREATE INDEX purchases_access ON rehab.purchases (user_id, product_id, mode) WHERE status = 'active';
CREATE TABLE rehab.mail_outbox (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL UNIQUE REFERENCES rehab.orders(id),
  recipient text NOT NULL,
  kind text NOT NULL CHECK (kind = 'purchase_access'),
  -- No arbitrary payload, passwords, reset tokens or payment signatures.
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  available_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE rehab.sessions (
  token_hash text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES rehab.users(id),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz
);
-- Actual dump's videos belong to users, not products. Course binding is separate.
CREATE TABLE rehab.videos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES rehab.users(id),
  title text NOT NULL,
  description text,
  file_path text NOT NULL,
  thumbnail_path text,
  size bigint,
  duration integer,
  mime_type text,
  views integer DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE rehab.course_videos (
  product_id uuid NOT NULL REFERENCES rehab.products(id),
  lesson_key text NOT NULL,
  video_id uuid NOT NULL REFERENCES rehab.videos(id),
  provider_id text,
  ready boolean NOT NULL DEFAULT false,
  PRIMARY KEY (product_id, lesson_key)
);
REVOKE ALL ON ALL TABLES IN SCHEMA rehab FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA rehab FROM PUBLIC;
COMMIT;
